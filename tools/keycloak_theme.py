"""打包官方 Keycloak 主题扩展，并校验随 Helm / 离线包交付的静态副本。"""

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
VALUES = ROOT / "deploy/components/keycloak/values/theme.yaml"


def theme_files() -> dict[str, str]:
    source = ROOT / "extensions/keycloak/themes/contexture/login"
    identity = ROOT / "packages/ui/identity"
    files = {
        p.relative_to(source).as_posix(): p.read_text()
        for p in sorted(source.rglob("*"))
        if p.is_file()
    }
    for path in sorted(identity.iterdir()):
        if path.suffix in {".css", ".svg"}:
            files[f"resources/identity/{path.name}"] = path.read_text()
    copy = json.loads((identity / "copy.zh-CN.json").read_text())
    serialized = json.dumps(copy, ensure_ascii=False).replace("<", "\\u003c")
    script = "resources/js/contexture.js"
    files[script] = f"window.CONTEXTURE_LOGIN_COPY = {serialized};\n" + files[script]
    # 本期自有文案为简体中文，不修改共享 realm 的全局语言设置。
    for locale in ("en", "zh_CN"):
        files[f"messages/messages_{locale}.properties"] = files["messages/messages.properties"]
    return dict(sorted(files.items()))


def values_text() -> str:
    return (
        "# Generated by python -m tools.keycloak_theme --write-values; do not edit.\n"
        + yaml.safe_dump({"theme": {"files": theme_files()}}, allow_unicode=True, sort_keys=True)
    )


def write_theme(output: Path) -> Path:
    destination = output / "contexture"
    for name, content in theme_files().items():
        target = destination / "login" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    return destination


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    actions = parser.add_mutually_exclusive_group(required=True)
    actions.add_argument("--bundle", type=Path)
    actions.add_argument("--check", action="store_true")
    actions.add_argument("--write-values", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        if not VALUES.is_file() or VALUES.read_text() != values_text():
            print("Keycloak 主题部署副本过期，请运行 --write-values")
            return 1
        print("Keycloak 主题部署副本一致")
    elif args.write_values:
        VALUES.write_text(values_text())
        print(f"主题部署副本已更新：{VALUES.relative_to(ROOT)}")
    else:
        print(write_theme(args.bundle))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
